#!/usr/bin/env python3
"""Worked example for docs/WAIVER_PRIORITY_EXAMPLE.md (owner ruling L1, Edition 8.55): the waiver claim order of all 48 clubs, Ambassador clubs
included, just before and just after the Week 4 transition of a real second season, and the proof that trading a draft pick moves no waiver
priority. Read-only apart from the one pick trade it performs on its own throwaway league. Prints Markdown.

    python3 tools/show_waiver_example.py [--seed 1]
"""
import argparse
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "src"))
from dfl import standings  # noqa: E402
from dfl.year import Universe  # noqa: E402


def run_to(u, year, key):
    while not (u.fired and u.fired[-1][0] == year and u.fired[-1][2] == key):
        u.step_event()


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--seed", type=int, default=1)
    a = ap.parse_args()
    u = Universe(os.path.join(ROOT, "data", "season1"), seed=a.seed, engine=False, spatial=False)
    run_to(u, 2001, "week_3")
    before = u.waiver_priority()                      # the order used for the paid week that follows league week 3
    draft_order = list(u.draft_order)
    run_to(u, 2001, "week_4")
    after = u.waiver_priority()                       # the order used for the paid week that follows league week 4
    run = u.run
    tour = set(run.ambassadors)
    rec = standings.tally(run.active, run.games)
    assert len(before) == len(after) == 48 and before == draft_order and sorted(before) == sorted(after)
    assert [c for c in before if c in tour] == [c for c in after if c in tour]
    assert all(before.index(c) == after.index(c) for c in tour)

    # now trade first-round picks and show that nothing in the order moves
    first, last = after[0], after[-1]
    L = u.L
    pick_a, pick_b = (2002, 1, first), (2002, 1, last)
    assert L.trade_open() and pick_a in L.clubs[first].picks and pick_b in L.clubs[last].picks
    L.trade(first, [], last, [], a_picks=[pick_a], b_picks=[pick_b])
    owner = lambda pk: next(c for c, club in L.clubs.items() if pk in club.picks)
    assert (owner(pick_a), owner(pick_b)) == (last, first)
    after_trade = u.waiver_priority()
    assert after_trade == after

    print(f"# Worked example: waiver claim order of all 48 clubs (seed {a.seed}, Season 2 = league year 2001)\n")
    print("Generated by `python3 tools/show_waiver_example.py --seed 1` (about 30 seconds; the same seed gives the same table). Season 2 is the first "
          "season with a real previous draft order, so it is the first in which the transition can be seen.\n")
    print("## What \"prior draft slot\" means (owner ruling L1)\n")
    print("It is **the club's own slot**, not a traded pick. The previous season's draft order is a list of *clubs*: the eight returning Ambassadors "
          "in lottery order, then the non-playoff clubs worst record first, then the playoff clubs by how far they went. A draft pick is a "
          "(year, round, original club) token and the slot it takes depends on its original club alone; owning another club's first-round pick "
          "changes who *selects* at that slot, never whose waiver place it is. `Universe.waiver_priority` reads only the list of clubs and never "
          "looks at pick ownership, so **trading picks cannot transfer waiver priority** (proved at the end of this page and by "
          "`tests/test_waiver_priority.py`).\n")
    print("Two periods, one rule each:\n")
    print("1. **Until four league weeks have finished** the order is last season's draft order, club by club.")
    print("2. **From the paid week after league week 4** the 40 clubs at home are ordered by this season's standings, worst record first "
          "(the league tiebreak cascade, the seeded draw last). The eight Ambassador clubs have no place in the home standings, so each keeps "
          "exactly the place her own draft slot gave her; the home clubs fill the remaining 40 places in standings order.\n")
    print("Place 1 claims first. **A** marks a club away on the Ambassador Tour this season (the eight clubs exiled after Season 1).\n")
    print("| Place | Before: last season's draft order | After league week 4: standings | Record (W-L-T after 4 weeks) | Places moved up (+) or down (-) |")
    print("|---:|---|---|---|---:|")
    for i, (b, c) in enumerate(zip(before, after)):
        r = rec.get(c)
        recs = "Tour: no home standings" if c in tour else f"{r.w}-{r.l}-{r.t}"
        mark = lambda x: f"{x} **A**" if x in tour else x
        moved = "" if before.index(c) == i else f"{before.index(c) - i:+d}"
        print(f"| {i + 1} | {mark(b)} | {mark(c)} | {recs} | {moved} |")
    print(f"\nAmbassador clubs keep their places exactly ({', '.join(f'{c}: {before.index(c) + 1}' for c in sorted(tour, key=before.index))}); "
          f"the 40 clubs at home share the other 40 places, reordered worst record first.\n")
    print("## Pick trades do not move waiver priority\n")
    print(f"Immediately afterwards, in the same league, `{first}` (place 1) and `{last}` (place 48) swapped their 2002 first-round picks. "
          f"`{first}` now owns `{last}`'s pick and `{last}` owns `{first}`'s. The waiver order recomputed after the trade is **identical** in all "
          f"48 places: {after_trade == after}.")


if __name__ == "__main__":
    main()
